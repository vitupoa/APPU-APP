# Get all TypeScript files in src directory (excluding generated files)
$files = Get-ChildItem -Path "src" -Filter "*.ts" -Recurse | Where-Object { $_.FullName -notmatch "\\generated\\" }

$totalFiles = $files.Count
$processedFiles = 0
$modifiedFiles = 0

Write-Host "Found $totalFiles TypeScript files to process..."
Write-Host ""

foreach ($file in $files) {
    $processedFiles++
    $content = Get-Content -Path $file.FullName -Raw
    $originalContent = $content
    $fileModified = $false
    
    # Apply all replacements
    foreach ($pattern in $accessorMapping.Keys) {
        $replacement = $accessorMapping[$pattern]
        if ($content -match $pattern) {
            $content = $content -replace $pattern, $replacement
            $fileModified = $true
        }
    }
    
    # Write back if modified
    if ($fileModified) {
        Set-Content -Path $file.FullName -Value $content -NoNewline
        $modifiedFiles++
        Write-Host "[$processedFiles/$totalFiles] Modified: $($file.FullName)"
    }
    
    # Progress indicator
    if ($processedFiles % 50 -eq 0) {
        Write-Host "Progress: $processedFiles/$totalFiles files processed, $modifiedFiles modified"
    }
}

Write-Host ""
Write-Host "========================================="
Write-Host "Replacement complete!"
Write-Host "Total files processed: $totalFiles"
Write-Host "Total files modified: $modifiedFiles"
Write-Host "========================================="
